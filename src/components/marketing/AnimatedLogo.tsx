/**
 * The marketing nav's logo, animated (globals.css "Logo"): it lands from a
 * soft blur, the ring mark turns one notch into place, the letters rise one
 * by one, the dot of the "i" drops in, then a sheen crosses once. Hovering
 * turns the ring another notch — always forward, and since the ring is
 * 3-fold symmetric it always lands exactly as drawn. `light` = white (over
 * dark sections); the color change is a smooth transition.
 */
export default function AnimatedLogo({ light = false, height = 30, className }: { light?: boolean; height?: number; className?: string }) {
  const id = useId().replace(/[^a-zA-Z0-9_-]/g, "");
  const mark = useRef<SVGGElement>(null);
  const turns = useRef(0);
  const turn = () => {
    const m = mark.current;
    if (!m || window.matchMedia("(prefers-reduced-motion: reduce)").matches) return;
    turns.current += 1;
    m.style.rotate = `${turns.current * 120}deg`;
  };
  const sheen = { stopColor: "rgb(var(--brand-300))" };
  return (
    <svg
      viewBox="0 0 1300 250"
      width={(height * 1300) / 250}
      height={height}
      className={cn("mk-logo", light && "is-light", className)}
      onPointerEnter={turn}
      aria-hidden
      focusable="false"
    >
      <defs>
        <clipPath id={`${id}-shape`}>{SHAPES.map((p, i) => <path key={i} d={p} />)}</clipPath>
        <linearGradient id={`${id}-sheen`}>
          <stop offset="0" style={{ ...sheen, stopOpacity: 0 }} />
          <stop offset=".5" style={{ ...sheen, stopOpacity: 0.9 }} />
          <stop offset="1" style={{ ...sheen, stopOpacity: 0 }} />
        </linearGradient>
      </defs>
      <g ref={mark} className="mk-logo__mark">
        {ARCS.map((p, i) => <path key={i} d={p} fill="currentColor" />)}
      </g>
      {LETTERS.map((p, i) => (
        <path key={i} d={p} fill="currentColor" className="mk-logo__letter" style={{ ["--i" as string]: i }} />
      ))}
      <path d={DOT} fill="currentColor" className="mk-logo__dot" />
      <g clipPath={`url(#${id}-shape)`}>
        <rect className="mk-logo__sheen" x={-300} y={-30} width={220} height={310} fill={`url(#${id}-sheen)`} />
      </g>
    </svg>
  );
}
